const TOTAL_ARTICLES = 35000; // generated by the publish job
const canonicalSlug = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.pathname === "/") return new Response(`<a href="/article/example">${TOTAL_ARTICLES} articles</a>`, { headers: { "content-type": "text/html" } });
    if (!url.pathname.startsWith("/article/")) return new Response("Not found", { status: 404 });
    const slug = url.pathname.slice(9);
    if (!canonicalSlug.test(slug)) return new Response("Not found", { status: 404 });
    const row = await env.DB.prepare("SELECT title, body FROM articles WHERE slug = ? LIMIT 1").bind(slug).first();
    return row ? Response.json(row) : new Response("Not found", { status: 404 });
  },
};
